"""Serialized reconstruction of the SatNOGS flowgraphs-1.5 FSK front end.

The historical graph contains a split AFC path.  Running that split through a
modern GNU Radio thread-per-block scheduler introduces small floating-point
differences between runs.  This module executes the same enabled blocks in a
fixed topological order and materializes each intermediate vector.  The moving
average's source-level ``max_iter=4096`` recurrence is executed with fixed
4096-sample work partitions; the remaining individual GNU Radio blocks are
retained.  Scheduler partitioning is therefore removed as an experimental axis.

This is a GNU Radio 3.10 runtime substitute for the unpinned historical 3.8
runtime, not a claim of bit-exact historical execution.
"""

