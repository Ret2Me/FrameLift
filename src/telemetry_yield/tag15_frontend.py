def deterministic_moving_average_ff(
    values: Sequence[float],
    *,
    length: int,
    scale: float,
    max_iter: int,
):
    """Execute GNU Radio's scalar moving-average recurrence deterministically.

    GNU Radio recomputes the float accumulator at every scheduler ``work``
    call, and caps each call at ``max_iter``.  Different scheduler partitions
    therefore change low-order float bits.  This implementation freezes calls
    to consecutive chunks of exactly ``max_iter`` items and mirrors the 3.8 and
    3.10 source recurrence using float32 operations.
    """

    import numpy as np

    source = np.asarray(values, dtype=np.float32)
    if source.ndim != 1 or length < 1 or max_iter < 1:
        raise ValueError("invalid moving-average input or parameters")
    padded = np.concatenate(
        (np.zeros(length - 1, dtype=np.float32), source)
    )
    output = np.empty(source.size, dtype=np.float32)
    scale32 = np.float32(scale)
    for start in range(0, source.size, max_iter):
        stop = min(start + max_iter, source.size)
        accumulator = np.float32(0.0)
        for index in range(start, start + length - 1):
            accumulator = np.float32(accumulator + padded[index])
        for output_index in range(start, stop):
            entering = padded[output_index + length - 1]
            accumulator = np.float32(accumulator + entering)
            output[output_index] = np.float32(accumulator * scale32)
            accumulator = np.float32(accumulator - padded[output_index])
    return output


def run_tag15_preclock(
    iq: Sequence[complex],
    *,
    spec: Tag15FrontendSpec = Tag15FrontendSpec(),
    max_noutput_items: int = 8_192,
):
    """Run the enabled tag-1.5 FSK blocks through the long DC blocker.

    Each block is run in isolation and the AFC split is joined by array index.
    This preserves block-level behavior while making execution order explicit.
    """

    import numpy as np

    analog, blocks, _, gr_filter, gr, _, _ = _require_gnuradio()
    values = np.asarray(iq, dtype=np.complex64)
    if values.ndim != 1 or values.size < 4_096:
        raise ValueError("IQ must be a one-dimensional window of at least 4096 samples")
    if values.size % spec.channel_decimation:
        raise ValueError("IQ length must be divisible by channel decimation")
    if not np.all(np.isfinite(values)):
        raise ValueError("IQ must be finite")
    if max_noutput_items < 1:
        raise ValueError("max_noutput_items must be positive")
    if spec.iq_rate_hz != spec.baudrate * spec.graph_decimation:
        raise ValueError("tag-1.5 rate contract is not satisfied")
    if spec.channel_decimation != spec.graph_decimation // 2:
        raise ValueError("tag-1.5 channel decimation contract is not satisfied")

    relaxed_taps, channel_taps = tag15_filter_taps(spec)
    stages: list[tuple[str, object]] = [("input", values)]
    relaxed = _run_complex_to_complex(
        values,
        lambda: gr_filter.fir_filter_ccf(1, relaxed_taps),
        max_noutput_items=max_noutput_items,
    )
    stages.append(("relaxed_lpf", relaxed))
    afc_discriminator = _run_complex_to_float(
        relaxed,
        lambda: analog.quadrature_demod_cf(spec.afc_discriminator_gain),
        max_noutput_items=max_noutput_items,
    )
    stages.append(("afc_discriminator", afc_discriminator))
    afc_average = deterministic_moving_average_ff(
        afc_discriminator,
        length=spec.afc_average_length,
        scale=1.0 / spec.afc_average_length,
        max_iter=4_096,
    )
    stages.append(("afc_moving_average", afc_average))
    afc_vco = _run_float_to_complex_vco(
        afc_average,
        sample_rate_hz=spec.iq_rate_hz,
        sensitivity=spec.afc_vco_sensitivity,
        max_noutput_items=max_noutput_items,
    )
    stages.append(("afc_vco", afc_vco))

    delayed = np.zeros(values.size, dtype=np.complex64)
    delayed[spec.signal_delay_samples :] = values[: -spec.signal_delay_samples]
    stages.append(("signal_delay", delayed))
    corrected = np.asarray(delayed * afc_vco, dtype=np.complex64)
    stages.append(("afc_corrected", corrected))
    channel = _run_complex_to_complex(
        corrected,
        lambda: gr_filter.fir_filter_ccf(
            spec.channel_decimation,
            channel_taps,
        ),
        max_noutput_items=max_noutput_items,
    )
    stages.append(("channel_lpf_decimated", channel))
    discriminator = _run_complex_to_float(
        channel,
        lambda: analog.quadrature_demod_cf(spec.discriminator_gain),
        max_noutput_items=max_noutput_items,
    )
    stages.append(("fsk_discriminator", discriminator))
    preclock = _run_float_to_float(
        discriminator,
        lambda: gr_filter.dc_blocker_ff(spec.dc_blocker_length, True),
        max_noutput_items=max_noutput_items,
    )
    stages.append(("dc_blocker_long", preclock))

    metrics = Tag15FrontendMetrics(
        input_complex_samples=int(values.size),
        output_float_samples=int(preclock.size),
        stage_sample_counts=tuple(
            (name, int(stage.size)) for name, stage in stages
        ),
        stage_sha256=tuple(
            (name, _sha256_array(stage)) for name, stage in stages
        ),
    )
    return preclock, metrics


def _run_float_to_complex_vco(
    values,
    *,
    sample_rate_hz: float,
    sensitivity: float,
    max_noutput_items: int,
):
    _, blocks, _, _, gr, _, _ = _require_gnuradio()
    return _run_float_to_complex(
        values,
        lambda: blocks.vco_c(sample_rate_hz, sensitivity, 1.0),
        max_noutput_items=max_noutput_items,
    )


