@dataclass(frozen=True)
class Tag15FrontendSpec:
    """Frozen enabled-block parameters from ``generic/fsk.grc`` tag 1.5."""

    iq_rate_hz: int = 57_600
    baudrate: int = 9_600
    graph_decimation: int = 6
    channel_decimation: int = 3
    relaxed_cutoff_hz: float = 12_000.0
    relaxed_transition_hz: float = 4_800.0
    afc_discriminator_gain: float = 1.0
    afc_average_length: int = 1_024
    afc_vco_sensitivity: float = -57_600.0
    signal_delay_samples: int = 512
    channel_cutoff_hz: float = 6_000.0
    channel_transition_hz: float = 1_200.0
    discriminator_gain: float = 1.2
    dc_blocker_length: int = 1_024
    clock_omega: float = 2.0
    clock_gain_omega: float = 2.0 * 3.141592653589793 / 100.0
    clock_mu: float = 0.5
    clock_gain_mu: float = 0.5 / 8.0
    clock_omega_relative_limit: float = 0.01
    iq_normalization_scale: float = 16_768.0


@dataclass(frozen=True)
class Tag15FrontendMetrics:
    """Hashes and sizes for every materialized front-end stage."""

    input_complex_samples: int
    output_float_samples: int
    stage_sample_counts: tuple[tuple[str, int], ...]
    stage_sha256: tuple[tuple[str, str], ...]


def _sha256_array(values) -> str:
    return hashlib.sha256(values.tobytes(order="C")).hexdigest()


def _require_gnuradio():
    try:
        from gnuradio import analog, blocks, digital, filter as gr_filter, gr
        from gnuradio.fft import window
        from gnuradio.filter import firdes
    except ImportError as error:  # pragma: no cover - depends on host runtime
        raise RuntimeError("GNU Radio is required for the tag-1.5 reconstruction") from error
    return analog, blocks, digital, gr_filter, gr, window, firdes


def tag15_filter_taps(
    spec: Tag15FrontendSpec = Tag15FrontendSpec(),
):
    """Return the exact taps generated by the installed GNU Radio firdes.

    The tag-1.5 graph specifies cutoff, transition width, Hamming window, and
    beta rather than literal taps.  The generated vectors are kept as float32,
    matching ``fir_filter_ccf``.
    """

    import numpy as np

    _, _, _, _, _, window, firdes = _require_gnuradio()
    relaxed = np.asarray(
        firdes.low_pass(
            1.0,
            spec.iq_rate_hz,
            spec.relaxed_cutoff_hz,
            spec.relaxed_transition_hz,
            window.WIN_HAMMING,
            6.76,
        ),
        dtype=np.float32,
    )
    channel = np.asarray(
        firdes.low_pass(
            1.0,
            spec.iq_rate_hz,
            spec.channel_cutoff_hz,
            spec.channel_transition_hz,
            window.WIN_HAMMING,
            6.76,
        ),
        dtype=np.float32,
    )
    return relaxed, channel


def read_tag15_c16le_window(
    path: str | Path,
    *,
    start_seconds: float,
    duration_seconds: float,
    spec: Tag15FrontendSpec = Tag15FrontendSpec(),
):
    """Read a bounded little-endian interleaved-IQ window as complex64."""

    import numpy as np

    if start_seconds < 0 or duration_seconds <= 0:
        raise ValueError("invalid IQ window")
    if spec.iq_rate_hz <= 0 or spec.iq_normalization_scale <= 0:
        raise ValueError("invalid sample format")
    source = Path(path)
    start_sample = int(round(start_seconds * spec.iq_rate_hz))
    sample_count = int(round(duration_seconds * spec.iq_rate_hz))
    raw = np.fromfile(
        source,
        dtype="<i2",
        count=sample_count * 2,
        offset=start_sample * 4,
    )
    if raw.size != sample_count * 2:
        raise ValueError("window extends beyond IQ file")
    pairs = raw.reshape(-1, 2)
    real = pairs[:, 0].astype(np.float32)
    imag = pairs[:, 1].astype(np.float32)
    return np.asarray(
        (real + 1j * imag) / np.float32(spec.iq_normalization_scale),
        dtype=np.complex64,
    )


def _run_complex_to_complex(values, make_block, *, max_noutput_items: int):
    import numpy as np

    _, blocks, _, _, gr, _, _ = _require_gnuradio()
    top = gr.top_block("tag15_serialized_cc")
    source = blocks.vector_source_c(values.tolist(), False)
    block = make_block()
    sink = blocks.vector_sink_c()
    top.connect(source, block, sink)
    top.run(max_noutput_items=max_noutput_items)
    return np.asarray(sink.data(), dtype=np.complex64)


