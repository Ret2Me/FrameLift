def run_tag15_clock(
    preclock: Sequence[float],
    *,
    spec: Tag15FrontendSpec = Tag15FrontendSpec(),
    max_noutput_items: int = 8_192,
) -> bytes:
    """Run the tag-1.5 M&M clock and binary slicer on one isolated vector."""

    import numpy as np

    _, blocks, digital, _, gr, _, _ = _require_gnuradio()
    values = np.asarray(preclock, dtype=np.float32)
    if values.ndim != 1 or values.size < 256 or not np.all(np.isfinite(values)):
        raise ValueError("preclock must be a finite one-dimensional vector")
    top = gr.top_block("tag15_serialized_clock")
    source = blocks.vector_source_f(values.tolist(), False)
    clock = digital.clock_recovery_mm_ff(
        spec.clock_omega,
        spec.clock_gain_omega,
        spec.clock_mu,
        spec.clock_gain_mu,
        spec.clock_omega_relative_limit,
    )
    slicer = digital.binary_slicer_fb()
    sink = blocks.vector_sink_b()
    top.connect(source, clock, slicer, sink)
    top.run(max_noutput_items=max_noutput_items)
    return bytes(sink.data())
